-- Profile list for owner/developer; users may see own profile.
create policy "profiles read own or managers" on public.profiles for select to authenticated
using (id=auth.uid() or public.current_role() in ('owner','developer'));
create policy "profiles update managers" on public.profiles for update to authenticated
using (public.current_role() in ('owner','developer'))
with check (public.current_role() in ('owner','developer'));

create policy "products read authenticated" on public.products for select to authenticated
using (public.current_role() is not null);
create policy "products update managers" on public.products for update to authenticated
using (public.has_permission('products.manage'))
with check (public.has_permission('products.manage'));
create policy "products insert managers" on public.products for insert to authenticated
with check (public.has_permission('products.manage'));
create policy "sales read managers or own" on public.sales for select to authenticated
using (public.current_role() in ('owner','developer') or cashier_id=auth.uid());
create policy "sale items read managers or own" on public.sale_items for select to authenticated
using (exists(select 1 from public.sales s where s.id=sale_id and (s.cashier_id=auth.uid() or public.current_role() in ('owner','developer'))));
create policy "stock movement read managers" on public.stock_movements for select to authenticated
using (public.current_role() in ('owner','developer'));
create policy "expenses read managers" on public.expenses for select to authenticated
using (public.current_role() in ('owner','developer') or public.has_permission('expenses.view'));
create policy "expenses insert permitted" on public.expenses for insert to authenticated
with check (public.has_permission('expenses.manage'));
create policy "settings read authenticated" on public.business_settings for select to authenticated
using (public.current_role() is not null);
create policy "settings update managers" on public.business_settings for update to authenticated
using (public.current_role() in ('owner','developer'))
with check (public.current_role() in ('owner','developer'));
create policy "settings insert managers" on public.business_settings for insert to authenticated
with check (public.current_role() in ('owner','developer'));
create policy "audit read managers" on public.audit_logs for select to authenticated
using (public.current_role() in ('owner','developer'));

